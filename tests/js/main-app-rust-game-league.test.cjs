'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');

const app = fs.readFileSync('assets/js/app-part-02.js', 'utf8');
const bridge = fs.readFileSync('assets/js/principia-wasm-physics.js', 'utf8');
const rust = fs.readFileSync('rust/src/game_league.rs', 'utf8');
const wasm = fs.readFileSync('rust/src/wasm_physics.rs', 'utf8');

test('AI league opponents and rank tiers are generated by Rust', () => {
  assert.match(app, /engine\.gameLeague\(\{operation:'bots',week\}\)/);
  assert.match(app, /async function loadPrincipiaLeagueBots\(week\)/);
  assert.doesNotMatch(app, /const names=\['NewtonBot'/);
  assert.doesNotMatch(app, /function leagueRank\(points\)/);
  assert.match(rust, /pub fn bots\(week: &str\)/);
  assert.match(rust, /pub fn rank\(points: u64\)/);
});

test('AI league match scoring and state changes are Rust-owned and fail closed', () => {
  assert.match(app, /operation:'match',week:state\.week/);
  assert.match(app, /resultRoll:random\[1\]\/4294967296/);
  assert.match(app, /Điểm chưa được thay đổi/);
  assert.doesNotMatch(app, /const win=Math\.random\(\)<\.62/);
  assert.match(rust, /pub fn resolve_match\(/);
  assert.match(wasm, /game_league_json\(input_json: &str\)/);
  assert.match(bridge, /gameLeague:payload=>compute\('gameLeague',payload\)/);
});
